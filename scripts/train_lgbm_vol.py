"""
LightGBM vs HAR on next-hour realized volatility.

Reads TRAIN and VALIDATION only. The test window is not opened.

The question is narrow and worth stating plainly: given the same information
HAR gets, plus a lot more, does a gradient-boosted tree ensemble actually beat
a three-term linear regression? If it does not, the extra machinery is not
earning its place, and that is a result rather than a failure.

Splits
------
    inner-train  .. 2023-01-01   fit
    inner-val    2023-01-01 .. 2024-01-01   early stopping only
    validation   2024-01-01 .. 2025-07-01   reported
    test         held out, untouched

Early stopping uses a slice of TRAIN, never the validation set, so the reported
number is not tuned on the data it is measured against.

Usage
-----
    python scripts/train_lgbm_vol.py
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

import lightgbm as lgb
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from features.volatility import build            # noqa: E402
from forecasting.evaluation.metrics import qlike  # noqa: E402

INNER_END = "2023-01-01"
TRAIN_END = "2024-01-01"
VAL_END = "2025-07-01"

PARAMS = dict(
    objective="regression",
    metric="rmse",
    learning_rate=0.03,
    num_leaves=63,
    min_data_in_leaf=200,
    feature_fraction=0.8,
    bagging_fraction=0.8,
    bagging_freq=1,
    lambda_l2=1.0,
    verbosity=-1,
    seed=42,
)


def data_root() -> Path:
    env = os.environ.get("FORESIGHT_DATA_ROOT")
    return Path(env).expanduser() if env else ROOT / "data"


def main() -> int:
    df = pd.read_parquet(data_root() / "interim" / "binance_BTCUSDT_1m.parquet")
    df = df[df.ts < VAL_END]          # the test window is never even loaded

    print("building features ...")
    f = build(df)
    cols = [c for c in f.columns if c != "y"]
    print(f"{len(f):,} hourly rows, {len(cols)} features\n")

    tr = f[f.index < INNER_END]
    iv = f[(f.index >= INNER_END) & (f.index < TRAIN_END)]
    va = f[f.index >= TRAIN_END]
    print(f"inner-train {len(tr):,}   inner-val {len(iv):,}   validation {len(va):,}\n")

    model = lgb.train(
        PARAMS,
        lgb.Dataset(tr[cols], tr["y"]),
        num_boost_round=3000,
        valid_sets=[lgb.Dataset(iv[cols], iv["y"])],
        callbacks=[lgb.early_stopping(100, verbose=False)],
    )
    print(f"best iteration: {model.best_iteration}\n")

    # ------------------------------------------------- HAR, same rows -------
    har_cols = ["har_h", "har_d", "har_w"]
    Xtr = np.column_stack([np.ones(len(tr)), tr[har_cols].to_numpy()])
    beta, *_ = np.linalg.lstsq(Xtr, tr["y"].to_numpy(), rcond=None)
    Xva = np.column_stack([np.ones(len(va)), va[har_cols].to_numpy()])

    y = va["y"].to_numpy()
    preds = {
        "naive (RV_t)": va["har_h"].to_numpy(),
        "HAR": Xva @ beta,
        "LightGBM": model.predict(va[cols], num_iteration=model.best_iteration),
    }

    base = preds["naive (RV_t)"]
    ss_base = float(np.sum((y - base) ** 2))
    ss_har = float(np.sum((y - preds["HAR"]) ** 2))

    lines = []

    def say(t=""):
        print(t)
        lines.append(t)

    say("PRIMARY TARGET - log realized volatility, next hour")
    say(f"validation {va.index[0]:%Y-%m-%d} .. {va.index[-1]:%Y-%m-%d}  "
        f"({len(va):,} hours)\n")
    say(f"{'model':<16} {'RMSE':>8} {'MAE':>8} {'QLIKE':>8} "
        f"{'R2 vs naive':>12} {'R2 vs HAR':>11}")
    say("-" * 68)
    for name, p in preds.items():
        ss = float(np.sum((y - p) ** 2))
        r2n = "  (baseline)" if name.startswith("naive") else f"{1 - ss / ss_base:>+12.4f}"
        r2h = "  (baseline)" if name == "HAR" else f"{1 - ss / ss_har:>+11.4f}"
        say(f"{name:<16} {np.sqrt(np.mean((y - p) ** 2)):>8.4f} "
            f"{np.mean(np.abs(y - p)):>8.4f} "
            f"{qlike(np.exp(y), np.exp(p)):>8.4f} {r2n} {r2h}")

    say("\nNote: HAR here is refit on INNER-TRAIN (< 2023-01-01), the same rows")
    say("LightGBM sees, so the two are compared on identical information. In")
    say("BASELINES.md HAR is fit on the full train window (< 2024-01-01) and so")
    say("scores slightly better there (RMSE 0.3357 vs 0.3388). Both are correct;")
    say("this table is the fair head-to-head, that one is HAR at its best.")

    say("\nTop 15 features by gain:")
    imp = (pd.Series(model.feature_importance("gain"), index=cols)
             .sort_values(ascending=False))
    total = imp.sum()
    for name, v in imp.head(15).items():
        say(f"  {name:<18} {100 * v / total:>5.1f}%")

    out = ROOT / "forecasting" / "evaluation" / "LGBM-VS-HAR.md"
    out.write_text(
        "# LightGBM vs HAR - next-hour realized volatility\n\n"
        "*Generated by `scripts/train_lgbm_vol.py`. Train and validation only; "
        "the test window is not read.*\n\n```\n" + "\n".join(lines) + "\n```\n",
        encoding="utf-8")
    print(f"\nwrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
