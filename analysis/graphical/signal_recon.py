"""
Signal reconnaissance on BTCUSDT 1m log-returns.

Asks one question before any model is built: is there exploitable structure,
and at which horizon? The answer sets k, which is still unfixed.

TRAIN SPLIT ONLY. The test window is never read by this script. Recon that
peeks at the test set is how a research project fools itself before it starts:
every feature you choose afterwards is chosen knowing the answer.

Three correctness details that would otherwise silently corrupt the result
-------------------------------------------------------------------------
1. GAP-AWARE RETURNS. Consecutive rows are not always consecutive minutes --
   8,562 bars are missing across real Binance outages, the longest 33 hours.
   ln(C_t+1 / C_t) across such a gap is not a 1-minute return, so those are
   dropped rather than kept.
2. NON-OVERLAPPING k-BAR RETURNS. Overlapping k-bar returns are autocorrelated
   up to lag k-1 *by construction*. Measuring ACF on them would manufacture the
   signal being looked for, so k-bar returns are built on a non-overlapping
   grid.
3. ZERO-RETURN POINT MASS. 2.86% of minute bars have no price change at all.
   Reported, because it distorts any assumption of a continuous distribution.

Usage
-----
    python analysis/graphical/signal_recon.py            # charts + report
"""

from __future__ import annotations

import os
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]

# Chronological split, fixed here once. Test is held out and never read.
TRAIN_END = "2024-01-01"
VAL_END = "2025-07-01"

HORIZONS = [1, 5, 15, 60]
MAX_LAG = 60

# Validated categorical palette (dataviz reference instance, light mode).
# node scripts/validate_palette.js "#2a78d6,#eb6834,#1baf7a,#eda100" --mode light
# -> all checks pass; contrast WARN obliges direct labels + a table view, both shipped.
SERIES = ["#2a78d6", "#eb6834", "#1baf7a", "#eda100"]
INK, INK2, GRID, SURFACE = "#0b0b0b", "#52514e", "#dcdcd8", "#fcfcfb"


def data_root() -> Path:
    env = os.environ.get("FORESIGHT_DATA_ROOT")
    return Path(env).expanduser() if env else ROOT / "data"


def style(ax):
    """Recessive grid and axes; the data carries the ink."""
    ax.set_facecolor(SURFACE)
    ax.grid(True, color=GRID, linewidth=0.8, alpha=0.9)
    ax.set_axisbelow(True)
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    for s in ("left", "bottom"):
        ax.spines[s].set_color(GRID)
    ax.tick_params(colors=INK2, labelsize=9, length=0)


def bar_returns(df: pd.DataFrame, k: int) -> np.ndarray:
    """Non-overlapping k-minute log-returns, gap-aware.

    Returns spanning a missing bar are dropped: the pair (t, t+k) is kept only
    when every minute between them is present.
    """
    s = df.set_index("ts")["close"]
    if k == 1:
        r = np.log(s / s.shift(1))
        ok = s.index.to_series().diff() == pd.Timedelta("1min")
        return r[ok].dropna().to_numpy()

    # take every k-th bar on a strict k-minute grid
    grid = s.iloc[::k]
    r = np.log(grid / grid.shift(1))
    contiguous = grid.index.to_series().diff() == pd.Timedelta(minutes=k)
    # and require the underlying minutes to be complete across each span
    counts = s.resample(f"{k}min").size().reindex(grid.index, fill_value=0)
    full = counts.shift(1).fillna(0).astype(int) >= k
    return r[contiguous & full].dropna().to_numpy()


def acf(x: np.ndarray, max_lag: int) -> np.ndarray:
    x = x - x.mean()
    denom = float(x @ x)
    return np.array([float(x[l:] @ x[:-l]) / denom for l in range(1, max_lag + 1)])


def main() -> int:
    src = data_root() / "interim" / "binance_BTCUSDT_1m.parquet"
    df = pd.read_parquet(src)

    train = df[df.ts < TRAIN_END].reset_index(drop=True)
    n_val = int(((df.ts >= TRAIN_END) & (df.ts < VAL_END)).sum())
    n_test = int((df.ts >= VAL_END).sum())

    out = ROOT / "analysis" / "graphical"
    lines: list[str] = []

    def say(s=""):
        print(s)
        lines.append(s)

    say("# Signal reconnaissance — BTCUSDT 1m")
    say()
    say(f"*Generated by `analysis/graphical/signal_recon.py` from `{src.name}`.*")
    say("**Train split only.** The test window is not read by this script.")
    say()
    say("## Split")
    say()
    say("| Split | Range | Bars |")
    say("|---|---|---|")
    say(f"| train | {train.ts.min():%Y-%m-%d} .. {TRAIN_END} | {len(train):,} |")
    say(f"| validation | {TRAIN_END} .. {VAL_END} | {n_val:,} |")
    say(f"| test (held out) | {VAL_END} .. {df.ts.max():%Y-%m-%d} | {n_test:,} |")
    say()

    # ------------------------------------------------- 1. ACF by horizon ----
    rets = {k: bar_returns(train, k) for k in HORIZONS}
    acfs = {k: acf(rets[k], MAX_LAG) for k in HORIZONS}

    say("## 1. Autocorrelation of log-returns, by horizon")
    say()
    say("Non-overlapping returns, so autocorrelation is not induced by construction.")
    say()
    say("| k (min) | n returns | ACF lag 1 | lag 2 | lag 3 | 95% band | lag-1 significant? |")
    say("|---|---|---|---|---|---|---|")
    for k in HORIZONS:
        n = len(rets[k])
        band = 1.96 / np.sqrt(n)
        a = acfs[k]
        sig = "**yes**" if abs(a[0]) > band else "no"
        say(f"| {k} | {n:,} | {a[0]:+.4f} | {a[1]:+.4f} | {a[2]:+.4f} | "
            f"±{band:.4f} | {sig} |")
    say()

    # Form: the finding lives in the first few lags, and beyond lag ~3 the
    # lines are noise around zero that converge and collide. Grouped bars over
    # lags 1-5 say the same thing legibly. Each series keeps its own
    # significance band, since n differs by two orders of magnitude across k.
    band1 = 1.96 / np.sqrt(len(rets[1]))
    n_lags = 5
    fig, ax = plt.subplots(figsize=(9, 4.6), facecolor=SURFACE)
    style(ax)
    width = 0.2
    idx = np.arange(1, n_lags + 1)
    for i, k in enumerate(HORIZONS):
        off = (i - 1.5) * width
        # 2px surface gap between adjacent fills
        ax.bar(idx + off, acfs[k][:n_lags], width=width * 0.88,
               color=SERIES[i], label=f"k = {k} min", zorder=3)
        b = 1.96 / np.sqrt(len(rets[k]))
        ax.plot([idx[0] + off - width / 2, idx[-1] + off + width / 2], [-b, -b],
                color=INK2, linewidth=0.9, linestyle=(0, (3, 3)), zorder=4)
    ax.axhline(0, color=INK2, linewidth=1, zorder=5)
    ax.annotate("dashed = 95% significance floor for that series",
                xy=(0.015, 0.055), xycoords="axes fraction", color=INK2, fontsize=8.5)
    ax.set_xticks(idx)
    ax.set_xlabel("lag", color=INK2, fontsize=10)
    ax.set_ylabel("autocorrelation", color=INK2, fontsize=10)
    ax.set_title("Lag-1 return autocorrelation is negative at every horizon, "
                 "then dies",
                 color=INK, fontsize=12, fontweight="bold", loc="left", pad=12)
    leg = ax.legend(frameon=False, fontsize=9, loc="lower right", ncols=4)
    for t in leg.get_texts():
        t.set_color(INK2)
    fig.tight_layout()
    fig.savefig(out / "recon-acf-returns.png", dpi=150, facecolor=SURFACE)
    plt.close(fig)

    # ------------------------------------------ 2. volatility clustering ----
    r1 = rets[1]
    a_r, a_abs = acf(r1, MAX_LAG), acf(np.abs(r1), MAX_LAG)
    say("## 2. Volatility clustering")
    say()
    say("| lag | ACF of r | ACF of \\|r\\| |")
    say("|---|---|---|")
    for l in (1, 5, 15, 30, 60):
        say(f"| {l} | {a_r[l-1]:+.4f} | **{a_abs[l-1]:+.4f}** |")
    say()

    fig, ax = plt.subplots(figsize=(9, 4.6), facecolor=SURFACE)
    style(ax)
    lag = np.arange(1, MAX_LAG + 1)
    ax.plot(lag, a_abs, color=SERIES[1], linewidth=2, label="|r|  (volatility)")
    ax.plot(lag, a_r, color=SERIES[0], linewidth=2, label="r  (return)")
    ax.annotate("|r|", (lag[-1], a_abs[-1]), xytext=(6, 0), textcoords="offset points",
                color=SERIES[1], fontsize=10, va="center", fontweight="bold")
    ax.annotate("r", (lag[-1], a_r[-1]), xytext=(6, 0), textcoords="offset points",
                color=SERIES[0], fontsize=10, va="center", fontweight="bold")
    ax.axhspan(-band1, band1, color=GRID, alpha=0.55, zorder=0)
    ax.axhline(0, color=INK2, linewidth=1)
    ax.set_xlabel("lag (minutes)", color=INK2, fontsize=10)
    ax.set_ylabel("autocorrelation", color=INK2, fontsize=10)
    ax.set_title("Volatility is strongly predictable where direction is not",
                 color=INK, fontsize=12, fontweight="bold", loc="left", pad=12)
    ax.set_xlim(1, MAX_LAG + 4)
    leg = ax.legend(frameon=False, fontsize=9, loc="upper right")
    for t in leg.get_texts():
        t.set_color(INK2)
    fig.tight_layout()
    fig.savefig(out / "recon-vol-clustering.png", dpi=150, facecolor=SURFACE)
    plt.close(fig)

    # --------------------------------------------------- 3. seasonality ----
    t = train.copy()
    t["r"] = np.log(t.close / t.close.shift(1))
    t = t[t.ts.diff() == pd.Timedelta("1min")]
    by_hour = t.groupby(t.ts.dt.hour)["r"].agg(["mean", "std", "count"])
    by_dow = t.groupby(t.ts.dt.dayofweek)["r"].agg(["mean", "std"])

    say("## 3. Intraday and weekday seasonality (UTC)")
    say()
    hi, lo = by_hour["std"].idxmax(), by_hour["std"].idxmin()
    say(f"Volatility peaks at **{hi:02d}:00 UTC** ({by_hour['std'].max():.5f}) and "
        f"bottoms at **{lo:02d}:00 UTC** ({by_hour['std'].min():.5f}), a "
        f"**{by_hour['std'].max() / by_hour['std'].min():.2f}x** spread.")
    say()
    dows = ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"]
    say("| day | mean r | std r |")
    say("|---|---|---|")
    for i, d in enumerate(dows):
        say(f"| {d} | {by_dow['mean'].iloc[i]:+.2e} | {by_dow['std'].iloc[i]:.5f} |")
    say()

    fig, ax = plt.subplots(figsize=(9, 4.2), facecolor=SURFACE)
    style(ax)
    ax.bar(by_hour.index, by_hour["std"], color=SERIES[2], width=0.68)
    ax.set_xlabel("hour of day (UTC)", color=INK2, fontsize=10)
    ax.set_ylabel("std of 1-minute log-return", color=INK2, fontsize=10)
    ax.set_title("Intraday volatility: a real, stable session pattern",
                 color=INK, fontsize=12, fontweight="bold", loc="left", pad=12)
    ax.set_xticks(range(0, 24, 2))
    fig.tight_layout()
    fig.savefig(out / "recon-intraday.png", dpi=150, facecolor=SURFACE)
    plt.close(fig)

    # ----------------------------------------------- 4. regime stability ----
    say("## 4. Regime stability by year")
    say()
    y = train.copy()
    y["r"] = np.log(y.close / y.close.shift(1))
    y = y[y.ts.diff() == pd.Timedelta("1min")]
    g = y.groupby(y.ts.dt.year)["r"].agg(
        bars="count", std="std", kurt=lambda s: s.kurtosis(),
        zero=lambda s: (s == 0).mean())
    say("| year | bars | std | kurtosis | zero-return share |")
    say("|---|---|---|---|---|")
    for yr, row in g.iterrows():
        # bracket access throughout: row.kurt and row.std resolve to Series
        # METHODS, not the aggregated columns, and fail only at format time.
        say(f"| {yr} | {int(row['bars']):,} | {row['std']:.5f} | "
            f"{row['kurt']:,.0f} | {row['zero']:.1%} |")
    say()

    (out / "SIGNAL-RECON.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"\nwrote {out / 'SIGNAL-RECON.md'} + 3 charts")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
